import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const root = path.resolve(import.meta.dirname, "..");
const entry = path.join(root, "sidecar", "src", "index.ts");
const outfile = path.join(root, "src-tauri", "resources", "agent", "index.mjs");

mkdirSync(path.dirname(outfile), { recursive: true });

const minify = process.argv.includes("--minify");

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  minify,
  banner: { js: "// generated by scripts/build-sidecar.mjs, edit sidecar/src instead" },
  logLevel: "warning",
});

process.stdout.write(
  `sidecar: bundled -> ${path.relative(root, outfile)}${minify ? " (minified)" : ""}\n`,
);
